"""网页数据提取的提示词模板。"""

# 初始提取 prompt
WEB_EXTRACT_PROMPT = """你是一个网页数据提取助手。我会给你一段网页 HTML，你要从中提取结构化数据。

规则：
1. 识别页面里的主要数据列表（热搜榜、排行榜、文章列表等）
2. 提取每条记录的所有可见字段
3. 只输出 JSON 数组，不要解释，不要 markdown
4. 字段名用页面里的原始文字（如"标题"、"热度"、"排名"）
5. 如果有排名，从1开始编号
6. 最多提取 50 条记录

输出格式：
[{{"标题": "...", "热度": "...", "链接": "..."}}]

HTML 内容：
"""

# 提取质量不达标时，带反馈的重提 prompt
# 动态变量：
#   {feedback}  — 上一轮的问题反馈（如"只提取到3条，且热度字段全空"）
WEB_EXTRACT_FEEDBACK_PROMPT = """上一轮提取结果不理想：{feedback}

请重新分析 HTML，调整提取策略：
- 重点识别页面里的主要数据列表（热搜榜、排行榜、文章列表等）
- 确保每条记录的关键字段（标题、数值等）都有值，不要留空
- 如果页面是搜索结果，提取所有可见的结果项
- 只输出 JSON 数组，不要解释

HTML 内容：
"""
