"""网页数据提取的提示词模板。"""

# 初始提取 prompt
# 动态变量：
#   {instruction}  — 用户的原始需求描述（如"爬豆瓣Top50，要电影名、评分、导演"）
WEB_EXTRACT_PROMPT = """你是一个网页数据提取助手。我会给你一段已清洗的网页内容和用户的需求，你要从中提取用户需要的数据。

网页内容已按记录边界整理：通常每行是一条候选记录，可能保留 <a href="..."> 链接标签，
脚本、样式、导航等噪声标签已删除。链接字段请取 href 的值。

用户需求：{instruction}

规则：
1. 根据用户需求，识别内容里的主要数据列表（热搜榜、排行榜、文章列表、搜索结果等）
2. 提取用户明确要求的字段，字段名用用户需求里的说法（如用户要"电影名"就用"电影名"，要"评分"就用"评分"）
3. 如果用户没有明确指定字段，就提取每条记录的所有可见字段
4. 只输出 JSON 数组，不要解释，不要 markdown
5. 最多提取 50 条记录

输出格式：
[{{"电影名": "...", "评分": "...", "导演": "..."}}]

网页内容：
"""

# 提取质量不达标时，带反馈的重提 prompt
# 动态变量：
#   {instruction}  — 用户的原始需求描述
#   {feedback}     — 上一轮的问题反馈（如"只提取到3条，且评分字段全空"）
WEB_EXTRACT_FEEDBACK_PROMPT = """上一轮提取结果不理想：{feedback}

用户需求是：{instruction}

请重新分析网页内容，严格按照用户需求提取：
- 只提取用户明确要求的字段，字段名必须与用户需求一致
- 如果用户要求"电影名、评分、导演"，输出的每个对象必须有这三个键
- 链接类字段取 <a href="..."> 里的地址，不要只给文字
- 确保每条记录的关键字段都有值，不要留空
- 只输出 JSON 数组，不要解释

网页内容：
"""
